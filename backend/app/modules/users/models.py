import uuid
from datetime import datetime

from sqlalchemy import CheckConstraint, DateTime, String, Uuid, func, text
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class User(Base):
    """A registered account.

    username and email are stored lowercase. The application normalizes them before
    saving, and the CHECK constraints below reject anything that slips through.
    """

    __tablename__ = "users"
    __table_args__ = (
        # Final names become ck_users_<name>, see NAMING_CONVENTION.
        CheckConstraint(r"username ~ '^[a-z0-9_]{3,30}$'", name="username_format"),
        CheckConstraint("email = lower(email)", name="email_lowercase"),
        CheckConstraint("length(email) >= 3", name="email_min_length"),
        CheckConstraint("length(btrim(display_name)) > 0", name="display_name_not_blank"),
    )

    # Generated by PostgreSQL 18 (time-ordered UUID), so inserts from any client get an id.
    id: Mapped[uuid.UUID] = mapped_column(
        Uuid, primary_key=True, server_default=text("uuidv7()")
    )
    username: Mapped[str] = mapped_column(String(30), unique=True)
    email: Mapped[str] = mapped_column(String(254), unique=True)
    password_hash: Mapped[str] = mapped_column(String(255))  # Argon2 hash, never plaintext
    display_name: Mapped[str] = mapped_column(String(50))
    bio: Mapped[str] = mapped_column(String(160), server_default="")

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )
